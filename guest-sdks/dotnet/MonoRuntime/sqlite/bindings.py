"""Generate the runtime's managed-to-native bindings for SQLite from its C API.

Usage: bindings.py AST_JSON EXPORTS IMPORTS_CS CALLBACKS_C PROVIDED

AST_JSON is clang's JSON AST of sqlite3.h and EXPORTS the functions the built
archive defines, one per line. Applications bring their own SQLitePCLRaw, so
the runtime's P/Invoke table and interpreter thunks cannot come from scanning
its declarations. IMPORTS_CS declares every exported, non-variadic function
for module e_sqlite3, for the runtime build's generator to scan. CALLBACKS_C
defines a pool of native entry points for each callback shape the API takes,
which the runtime binds to whichever managed method a caller passes.
PROVIDED lists each declared function as MODULE!NAME, for the SDK's
native-import diagnostic.
"""

import json
import re
import sys

MODULE = "e_sqlite3"
# Native entry points per callback shape. One managed method takes one entry
# however many functions it registers; SQLitePCLRaw passes at most three
# methods of one shape.
CALLBACK_CAPACITY = 8


def main(ast_path, exports_path, imports_path, callbacks_path, provided_path):
    with open(ast_path, encoding="utf-8") as stream:
        ast = json.load(stream)
    with open(exports_path, encoding="utf-8") as stream:
        exports = {line.strip() for line in stream if line.strip()}
    typedefs = {
        node["name"]: node["type"].get("desugaredQualType", node["type"]["qualType"])
        for node in ast["inner"]
        if node.get("kind") == "TypedefDecl"
    }
    functions = {}
    callbacks = set()
    for node in ast["inner"]:
        if node.get("kind") != "FunctionDecl" or node["name"] not in exports or node.get("variadic"):
            continue
        parameters = [p["type"]["qualType"] for p in node.get("inner", []) if p.get("kind") == "ParmVarDecl"]
        result = node["type"]["qualType"].split("(", 1)[0].strip()
        functions[node["name"]] = (result, parameters)
        for parameter in parameters:
            shape = callback_shape(parameter, typedefs)
            if shape:
                callbacks.add(shape)
    if not functions:
        raise SystemExit("bindings.py: sqlite3.h declares none of the archive's exports")
    write(imports_path, imports(functions, typedefs))
    write(callbacks_path, pools(sorted(callbacks)))
    write(provided_path, "".join(f"{MODULE}!{name}\n" for name in sorted(functions)))


def resolve(c_type, typedefs):
    c_type = re.sub(r"\b(const|volatile)\b", "", c_type).strip()
    seen = set()
    while c_type in typedefs and c_type not in seen:
        seen.add(c_type)
        c_type = re.sub(r"\b(const|volatile)\b", "", typedefs[c_type]).strip()
    return " ".join(c_type.split())


def signature_char(c_type, typedefs):
    """The interpreter-to-native signature letter of a C type on wasm32."""
    c_type = resolve(c_type, typedefs)
    if "*" in c_type or "[" in c_type:
        return "I"
    if c_type == "void":
        return "V"
    if c_type in ("double",):
        return "D"
    if c_type in ("float",):
        return "F"
    if c_type in ("long long", "unsigned long long"):
        return "L"
    if c_type in ("int", "unsigned int", "char", "signed char", "unsigned char",
                  "short", "unsigned short", "long", "unsigned long"):
        return "I"
    raise SystemExit(f"bindings.py: no wasm32 signature for C type '{c_type}'")


def managed_type(c_type, typedefs):
    resolved = resolve(c_type, typedefs)
    letter = signature_char(c_type, typedefs)
    if letter == "I" and ("*" in resolved or "[" in resolved):
        return "nint"
    unsigned = resolved.startswith("unsigned")
    return {"V": "void", "D": "double", "F": "float",
            "L": "ulong" if unsigned else "long",
            "I": "uint" if unsigned else "int"}[letter]


def callback_shape(c_type, typedefs):
    """The signature of a function pointer parameter, or None."""
    c_type = resolve(c_type, typedefs)
    match = re.fullmatch(r"(.+?)\s*\(\*\)\((.*)\)", c_type)
    if not match:
        return None
    result, parameters = match.group(1), split_parameters(match.group(2))
    if parameters == ["void"]:
        parameters = []
    return signature_char(result, typedefs) + "".join(signature_char(p, typedefs) for p in parameters)


def split_parameters(text):
    parameters, depth, current = [], 0, ""
    for character in text:
        if character == "," and depth == 0:
            parameters.append(current.strip())
            current = ""
            continue
        depth += {"(": 1, ")": -1}.get(character, 0)
        current += character
    if current.strip():
        parameters.append(current.strip())
    return parameters


def imports(functions, typedefs):
    lines = [
        "// <auto-generated>bindings.py, from sqlite3.h and the functions e_sqlite3.a exports</auto-generated>",
        "using System.Runtime.InteropServices;",
        "",
        "namespace Isoplane.MonoRuntime;",
        "",
        "internal static class SqliteImports",
        "{",
    ]
    for name, (result, parameters) in sorted(functions.items()):
        if parameters == ["void"]:
            parameters = []
        arguments = ", ".join(f"{managed_type(p, typedefs)} p{i}" for i, p in enumerate(parameters))
        lines.append(f"    [DllImport(\"{MODULE}\")] internal static extern {managed_type(result, typedefs)} {name}({arguments});")
    lines.append("}")
    return "\n".join(lines) + "\n"


C_TYPES = {"I": "int32_t", "L": "int64_t", "F": "float", "D": "double", "V": "void"}


def pools(shapes):
    lines = [
        "/* Generated by bindings.py from the callback parameters in sqlite3.h. */",
        "#include <stdint.h>",
        "#include \"sqlite_callbacks.h\"",
        "",
    ]
    entries = []
    for shape in shapes:
        result, parameters = shape[0], shape[1:]
        lines.append(f"static IsoplaneCallbackTarget targets_{shape}[{CALLBACK_CAPACITY}];")
        names = []
        for slot in range(CALLBACK_CAPACITY):
            name = f"entry_{shape}_{slot}"
            names.append(name)
            declared = ", ".join(f"{C_TYPES[p]} a{i}" for i, p in enumerate(parameters)) or "void"
            pointers = ["(int32_t *)&result"] if result != "V" else []
            pointers += [f"(int32_t *)&a{i}" for i in range(len(parameters))]
            pointers.append(f"(int32_t *)targets_{shape}[{slot}].arg")
            entry_type = ", ".join("int32_t *" for _ in pointers)
            lines.append(f"static {C_TYPES[result]} {name}({declared})")
            lines.append("{")
            if result != "V":
                lines.append(f"    {C_TYPES[result]} result;")
            lines.append(f"    ((void (*)({entry_type}))targets_{shape}[{slot}].func)({', '.join(pointers)});")
            if result != "V":
                lines.append("    return result;")
            lines.append("}")
        lines.append(f"static void *const entries_{shape}[] = {{{', '.join(names)}}};")
        lines.append("")
        entries.append(f"    {{\"{shape}\", targets_{shape}, entries_{shape}, {CALLBACK_CAPACITY}, 0}},")
    lines.append("IsoplaneCallbackPool isoplane_sqlite_callback_pools[] = {")
    lines.extend(entries)
    lines.append("};")
    lines.append("const int isoplane_sqlite_callback_pool_count = sizeof(isoplane_sqlite_callback_pools) / sizeof(isoplane_sqlite_callback_pools[0]);")
    return "\n".join(lines) + "\n"


def write(path, contents):
    with open(path, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(contents)


if __name__ == "__main__":
    if len(sys.argv) != 6:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
