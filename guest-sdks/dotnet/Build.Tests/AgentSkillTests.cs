using System.Xml.Linq;
using Isoplane.Conformance;
using Xunit;

public sealed class AgentSkillTests : MsbuildTests
{
    [Fact]
    public async Task a_build_writes_the_skill_at_the_repository_root_with_a_section_for_each_part()
    {
        var repository = Repository(git: true);
        var result = await Run(Msbuild(Project(repository, parts: ["sdk", "aspnetcore"]), "-t:Build"));
        Assert.True(result.Exit == 0, result.Output);
        var skill = File.ReadAllText(Path.Combine(repository, ".agents/skills/isoplane/SKILL.md"));
        Assert.StartsWith("---\nname: isoplane\n", skill);
        Assert.Contains("<!-- Generated by Isoplane.Sdk 1.2.3 ", skill);
        Assert.True(skill.IndexOf("### Isoplane.Sdk", StringComparison.Ordinal) < skill.IndexOf("### Isoplane.AspNetCore", StringComparison.Ordinal), skill);
        Assert.True(File.Exists(Path.Combine(repository, ".agents/skills/isoplane/references/sdk/concepts/page.md")));
        Assert.True(File.Exists(Path.Combine(repository, ".claude/skills/isoplane/SKILL.md")), "the second directory must reach the skill, by link or by copy");
        Assert.False(Directory.Exists(Path.Combine(repository, "src/app/.agents")), "the skill belongs at the root, not beside the project");
    }

    [Fact]
    public async Task a_skills_directory_that_already_exists_gets_the_skill_inside_it_and_keeps_its_own()
    {
        var repository = Repository(git: true);
        var own = Path.Combine(repository, ".claude/skills/mine/SKILL.md");
        Directory.CreateDirectory(Path.GetDirectoryName(own)!);
        File.WriteAllText(own, "---\nname: mine\n---\n");
        var result = await Run(Msbuild(Project(repository, parts: ["sdk"]), "-t:Build"));
        Assert.True(result.Exit == 0, result.Output);
        Assert.Null(new DirectoryInfo(Path.Combine(repository, ".claude/skills")).LinkTarget);
        Assert.Equal("---\nname: mine\n---\n", File.ReadAllText(own));
        Assert.Contains("### Isoplane.Sdk", File.ReadAllText(Path.Combine(repository, ".claude/skills/isoplane/SKILL.md")));
    }

    [Fact]
    public async Task a_part_whose_package_left_the_project_is_removed_by_the_next_build()
    {
        var repository = Repository(git: true);
        Assert.Equal(0, (await Run(Msbuild(Project(repository, parts: ["sdk", "aspnetcore"]), "-t:Build"))).Exit);
        var result = await Run(Msbuild(Project(repository, parts: ["sdk"]), "-t:Build"));
        Assert.True(result.Exit == 0, result.Output);
        Assert.False(Directory.Exists(Path.Combine(repository, ".agents/skills/isoplane/references/aspnetcore")));
        Assert.DoesNotContain("### Isoplane.AspNetCore", File.ReadAllText(Path.Combine(repository, ".agents/skills/isoplane/SKILL.md")));
    }

    [Fact]
    public async Task an_edit_is_overwritten_and_an_unchanged_build_rewrites_nothing()
    {
        var repository = Repository(git: true);
        var project = Project(repository, parts: ["sdk"]);
        Assert.Equal(0, (await Run(Msbuild(project, "-t:Build"))).Exit);
        var skill = Path.Combine(repository, ".agents/skills/isoplane/SKILL.md");
        var written = File.ReadAllText(skill);
        var stamp = File.GetLastWriteTimeUtc(skill);
        Assert.Equal(0, (await Run(Msbuild(project, "-t:Build"))).Exit);
        Assert.Equal(stamp, File.GetLastWriteTimeUtc(skill));
        File.WriteAllText(skill, written + "\nMy own note.\n");
        Assert.Equal(0, (await Run(Msbuild(project, "-t:Build"))).Exit);
        Assert.Equal(written, File.ReadAllText(skill));
    }

    [Fact]
    public async Task the_writing_can_be_switched_off_and_redirected()
    {
        var repository = Repository(git: true);
        var off = await Run(Msbuild(Project(repository, ["sdk"], new XElement("IsoplaneWriteAgentSkill", "false")), "-t:Build"));
        Assert.True(off.Exit == 0 && !Directory.Exists(Path.Combine(repository, ".agents")), off.Output);
        var elsewhere = Path.Combine(directory, "elsewhere");
        var redirected = await Run(Msbuild(Project(repository, ["sdk"], new XElement("IsoplaneAgentSkillRoot", elsewhere),
            new XElement("IsoplaneAgentSkillDirectories", "skills")), "-t:Build"));
        Assert.True(redirected.Exit == 0, redirected.Output);
        Assert.True(File.Exists(Path.Combine(elsewhere, "skills/isoplane/SKILL.md")));
        Assert.False(Directory.Exists(Path.Combine(repository, ".agents")) || Directory.Exists(Path.Combine(elsewhere, ".claude")));
    }

    [Fact]
    public async Task a_solution_directory_nearer_than_a_git_entry_is_the_root()
    {
        var repository = Repository(git: false);
        Directory.CreateDirectory(Path.Combine(directory, ".git"));
        File.WriteAllText(Path.Combine(repository, "app.slnx"), "<Solution />");
        var result = await Run(Msbuild(Project(repository, parts: ["sdk"]), "-t:Build"));
        Assert.True(result.Exit == 0 && File.Exists(Path.Combine(repository, ".agents/skills/isoplane/SKILL.md")), result.Output);
    }

    private string Repository(bool git)
    {
        var repository = Directory.CreateDirectory(Path.Combine(directory, "repo")).FullName;
        if (git) Directory.CreateDirectory(Path.Combine(repository, ".git"));
        return repository;
    }

    /// <summary>A project two levels below the root, built with the SDK's skill targets against a stand-in for a package's skill files.</summary>
    private string Project(string repository, string[] parts, params XElement[] properties)
    {
        var build = Directory.CreateDirectory(Path.Combine(directory, "tools/Build")).FullName;
        var task = Directory.CreateDirectory(Path.Combine(directory, "tools/Conformance")).FullName;
        File.Copy(typeof(WriteAgentSkill).Assembly.Location, Path.Combine(task, "Isoplane.Conformance.dll"), overwrite: true);
        var targets = Path.Combine(build, "Isoplane.AgentSkill.targets");
        File.Copy(Path.Combine(SdkDirectory(), "Build/Isoplane.AgentSkill.targets"), targets, overwrite: true);
        var skill = Path.Combine(directory, "package/tools/skill");
        Directory.CreateDirectory(skill);
        File.WriteAllText(Path.Combine(skill, "SKILL.md"), "---\nname: isoplane\ndescription: Stand-in.\n---\n\n# Isoplane\n\n## References\n");
        foreach (var (name, title) in new[] { ("sdk", "Isoplane.Sdk"), ("aspnetcore", "Isoplane.AspNetCore") })
        {
            var part = Directory.CreateDirectory(Path.Combine(skill, "references", name, "concepts")).Parent!.FullName;
            File.WriteAllText(Path.Combine(part, "README.md"), $"### {title}\n\n- [Page](references/{name}/concepts/page.md)\n");
            File.WriteAllText(Path.Combine(part, "concepts/page.md"), $"# {title} page\n");
        }
        var project = Path.Combine(repository, "src/app/test.proj");
        Directory.CreateDirectory(Path.GetDirectoryName(project)!);
        new XDocument(new XElement("Project",
            new XElement("PropertyGroup", new XElement("IsoplaneSdkVersion", "1.2.3"), new XElement("IntermediateOutputPath", "obj/"), properties),
            new XElement("ItemGroup",
                new XElement("IsoplaneAgentSkillBase", new XAttribute("Include", Path.Combine(skill, "SKILL.md"))),
                parts.Select(part => new XElement("IsoplaneAgentSkillPart", new XAttribute("Include", Path.Combine(skill, "references", part)), new XAttribute("Name", part)))),
            new XElement("Import", new XAttribute("Project", targets)),
            new XElement("Target", new XAttribute("Name", "Build")))).Save(project);
        return project;
    }
}
