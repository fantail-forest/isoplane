using System.Text;
using Microsoft.Build.Framework;
using Microsoft.Build.Utilities;

namespace Isoplane.Conformance;

/// <summary>
/// Writes the <c>isoplane</c> agent skill into the repository of the project being built: the base
/// <c>SKILL.md</c> the SDK carries, extended with a section for each part the project's Isoplane
/// packages contribute, and those parts' reference files under <c>references/</c>. The first of
/// <see cref="Directories"/> holds the files; each other one links to it, or holds a copy where a
/// link cannot be made. Files are rewritten only when their content differs, so an unchanged build
/// leaves the repository untouched.
/// </summary>
public sealed class WriteAgentSkill : Microsoft.Build.Utilities.Task
{
    private const string SkillName = "isoplane";
    private const string Notice = "<!-- Generated by Isoplane.Sdk";

    /// <summary>The directory of the project being built, where the search for the root starts.</summary>
    [Required] public string ProjectDirectory { get; set; } = "";

    /// <summary>The directory the skill directories are created under; empty to find it from the project.</summary>
    public string Root { get; set; } = "";

    /// <summary>The skill directories relative to the root, separated by semicolons; the first is written, the others link to it.</summary>
    [Required] public string Directories { get; set; } = "";

    /// <summary>The <c>SKILL.md</c> the sections are appended to.</summary>
    [Required] public string Base { get; set; } = "";

    /// <summary>One directory per part, named by its <c>Name</c> metadata, each holding a <c>README.md</c> section and reference files.</summary>
    public ITaskItem[] Parts { get; set; } = [];

    /// <summary>The SDK version named in the generated notice.</summary>
    [Required] public string SdkVersion { get; set; } = "";

    /// <summary>Where the names of the parts this project wrote last time are kept, so a part whose package left the project is removed.</summary>
    [Required] public string ManifestFile { get; set; } = "";

    /// <summary>The directory the skill was written to.</summary>
    [Output] public string SkillDirectory { get; set; } = "";

    /// <inheritdoc />
    public override bool Execute()
    {
        var directories = Directories.Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        if (directories.Length == 0)
        {
            Log.LogError("isoplane: IsoplaneAgentSkillDirectories names no directory; set IsoplaneWriteAgentSkill to false to stop writing the skill.");
            return false;
        }
        if (!File.Exists(Base))
        {
            Log.LogError("isoplane: the SDK's skill base {0} is missing; reinstall the Isoplane.Sdk package.", Base);
            return false;
        }
        var parts = new List<(string Name, string Directory)>();
        foreach (var part in Parts)
        {
            var name = part.GetMetadata("Name");
            if (name.Length == 0 || !Directory.Exists(part.ItemSpec))
            {
                Log.LogError("isoplane: the skill part '{0}' at {1} is missing; reinstall the package that provides it.", name, part.ItemSpec);
                return false;
            }
            parts.Add((name, part.ItemSpec));
        }
        var root = Root.Length != 0 ? Path.GetFullPath(Root) : FindRoot(Path.GetFullPath(ProjectDirectory));
        var skill = Path.Combine(root, directories[0], SkillName);
        var changed = false;
        var previous = File.Exists(ManifestFile) ? File.ReadAllLines(ManifestFile) : [];
        foreach (var stale in previous.Except(parts.Select(part => part.Name), StringComparer.Ordinal))
        {
            var directory = Path.Combine(skill, "references", stale);
            if (!Directory.Exists(directory)) continue;
            Directory.Delete(directory, recursive: true);
            changed = true;
        }
        foreach (var (name, source) in parts)
            changed |= Synchronize(source, Path.Combine(skill, "references", name));
        changed |= WriteIfDifferent(Path.Combine(skill, "SKILL.md"), Assemble(skill));
        Directory.CreateDirectory(Path.GetDirectoryName(ManifestFile)!);
        File.WriteAllLines(ManifestFile, parts.Select(part => part.Name));
        foreach (var directory in directories.Skip(1))
            changed |= Link(Path.Combine(root, directory), skill);
        SkillDirectory = skill;
        Log.LogMessage(changed ? MessageImportance.Normal : MessageImportance.Low, "isoplane: agent skill {0} at {1}", changed ? "written" : "unchanged", skill);
        return true;
    }

    /// <summary>
    /// The nearest directory above the project holding a <c>.git</c> entry or a solution file, where a
    /// coding agent opens the code; else the project directory. The nearest, not the first repository:
    /// a <c>.git</c> far above, such as a home directory's dotfiles, must not claim a project below it.
    /// </summary>
    private static string FindRoot(string project)
    {
        for (var directory = new DirectoryInfo(project); directory is not null; directory = directory.Parent)
            if (Directory.Exists(Path.Combine(directory.FullName, ".git")) || File.Exists(Path.Combine(directory.FullName, ".git"))
                || directory.EnumerateFiles("*.sln").Any() || directory.EnumerateFiles("*.slnx").Any())
                return directory.FullName;
        return project;
    }

    /// <summary>Makes <paramref name="destination"/> hold exactly the files of <paramref name="source"/>.</summary>
    private static bool Synchronize(string source, string destination)
    {
        var changed = false;
        var wanted = new HashSet<string>(StringComparer.Ordinal);
        foreach (var file in Directory.EnumerateFiles(source, "*", SearchOption.AllDirectories))
        {
            var relative = Path.GetRelativePath(source, file);
            wanted.Add(relative);
            changed |= WriteIfDifferent(Path.Combine(destination, relative), File.ReadAllBytes(file));
        }
        if (Directory.Exists(destination))
            foreach (var file in Directory.EnumerateFiles(destination, "*", SearchOption.AllDirectories).ToArray())
                if (!wanted.Contains(Path.GetRelativePath(destination, file)))
                {
                    File.Delete(file);
                    changed = true;
                }
        return changed;
    }

    /// <summary>
    /// The base with the generated notice after its frontmatter, then the README of every part present
    /// under <c>references/</c>, the SDK's own first. Parts on disk, not only this project's, so that two
    /// projects of one repository with different packages extend the one skill instead of trading it.
    /// </summary>
    private string Assemble(string skill)
    {
        var text = File.ReadAllText(Base).Replace("\r\n", "\n").TrimEnd() + "\n";
        var end = text.StartsWith("---\n", StringComparison.Ordinal) ? text.IndexOf("\n---\n", 4, StringComparison.Ordinal) + 5 : 0;
        var notice = $"{Notice} {SdkVersion} when the project builds, and overwritten on every build. Put guidance of your\n" +
            "     own in a skill beside this one. IsoplaneWriteAgentSkill=false in the project file stops the writing; the section\n" +
            "     'This skill' below names the other properties. Commit this directory so that an agent working from a clone sees it. -->\n";
        var builder = new StringBuilder(text[..end]).Append(notice).Append(text[end..]);
        var references = Path.Combine(skill, "references");
        var sections = (Directory.Exists(references) ? Directory.EnumerateDirectories(references) : [])
            .Select(directory => Path.Combine(directory, "README.md")).Where(File.Exists)
            .OrderBy(readme => Path.GetFileName(Path.GetDirectoryName(readme)) == "sdk" ? 0 : 1)
            .ThenBy(readme => Path.GetFileName(Path.GetDirectoryName(readme)), StringComparer.Ordinal);
        foreach (var section in sections)
            builder.Append('\n').Append(File.ReadAllText(section).Replace("\r\n", "\n").TrimEnd()).Append('\n');
        return builder.ToString();
    }

    /// <summary>
    /// Points <paramref name="entry"/>, a skills directory such as <c>.claude/skills</c>, at the skill: as a
    /// link to the primary skills directory when it does not exist, as a link to the skill inside it when
    /// it is a directory of its own, and as a copy where the platform refuses the link. An entry that is
    /// already a link, or a skill of the same name that is not ours, is left alone.
    /// </summary>
    private bool Link(string entry, string skill)
    {
        var primary = Path.GetDirectoryName(skill)!;
        var info = new FileInfo(entry);
        if (info.Exists && info.LinkTarget is null && LooksLikeCheckedOutLink(info))
            info.Delete();
        if (!Directory.Exists(entry) && !File.Exists(entry))
            return MakeLink(entry, primary) || CopySkill(Path.Combine(entry, SkillName), skill);
        if (new DirectoryInfo(entry).LinkTarget is not null) return false;
        var child = Path.Combine(entry, SkillName);
        var existing = new DirectoryInfo(child);
        if (existing.Exists)
        {
            if (existing.LinkTarget is not null) return false;
            if (!IsOurs(child))
            {
                Log.LogWarning("isoplane: {0} holds a skill named {1} that the SDK did not write, so it is left as it is; the SDK's skill is at {2}.", entry, SkillName, skill);
                return false;
            }
            if (!MakeLink(child, skill, replace: true)) return CopySkill(child, skill);
            return true;
        }
        return MakeLink(child, skill) || CopySkill(child, skill);
    }

    /// <summary>A Git checkout without symbolic links writes a link as a file holding its target path.</summary>
    private static bool LooksLikeCheckedOutLink(FileInfo file)
    {
        if (file.Length > 1024) return false;
        var content = File.ReadAllText(file.FullName).Trim();
        return content.Length > 0 && !content.Contains('\n') && content.Contains("skills", StringComparison.Ordinal);
    }

    private bool MakeLink(string path, string target, bool replace = false)
    {
        var relative = Path.GetRelativePath(Path.GetDirectoryName(path)!, target);
        try
        {
            if (replace) Directory.Delete(path, recursive: true);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            Directory.CreateSymbolicLink(path, relative);
            return true;
        }
        catch (Exception error) when (error is IOException or UnauthorizedAccessException or PlatformNotSupportedException)
        {
            Log.LogMessage(MessageImportance.Normal, "isoplane: cannot link {0} to {1} ({2}); copying the skill instead.", path, relative, error.Message);
            return false;
        }
    }

    private bool CopySkill(string destination, string skill) => Synchronize(skill, destination);

    private static bool IsOurs(string directory)
    {
        var file = Path.Combine(directory, "SKILL.md");
        return File.Exists(file) && File.ReadAllText(file).Contains(Notice, StringComparison.Ordinal);
    }

    private static bool WriteIfDifferent(string path, string text) => WriteIfDifferent(path, new UTF8Encoding(false).GetBytes(text));

    private static bool WriteIfDifferent(string path, byte[] content)
    {
        if (File.Exists(path) && File.ReadAllBytes(path).AsSpan().SequenceEqual(content)) return false;
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllBytes(path, content);
        return true;
    }
}
