//! A template warmed at deploy-time preparation observes a trust-bundle
//! rotation. Local initialization prepares the .NET guest with bundle A
//! served, so the template carries the machine root store's cache of A; a
//! node serving bundle B activates that template, and the store lists B once
//! the guest clock passes the store's recheck interval, A until then.
//!
//! The guest clock is the harness's: pre-initialisation freezes it at zero,
//! and the reactor's slice clock is what the activated guest's stopwatch
//! reads, so "five seconds of guest time since the store was loaded" is
//! exactly the slice clock the test begins the dispatch at.

use std::path::Path;
use std::process::Command;

use rustls_pki_types::pem::PemObject;
use rustls_pki_types::CertificateDer;
use wisp_abi::config::InitSandbox;
use wisp_control::{PreInitRequest, PreInitializer};
use wisp_engine::{ModuleHash, PlatformFile, PlatformFiles};
use wisp_fixtures::GuestRuntime;
use wisp_harness::EmittedGuestLogs as _;
use wisp_harness::{Reactor, ReturnedGuest};
use wisp_host::egress::{DnsError, HostEgressPolicy};
use wisp_host::{InstanceId, Resolver};

/// Where every guest finds the platform's root bundle.
const BUNDLE_PATH: &str = "/etc/ssl/certs/ca-certificates.crt";

/// The store provider rechecks the bundle at its next use after five seconds
/// of guest time; pre-initialisation loaded it at guest time zero.
const PAST_RECHECK_MS: u64 = 6_000;
const WITHIN_RECHECK_MS: u64 = 1_000;

/// One self-signed root as the guest's store reports it.
struct Root {
    pem: String,
    thumbprint: String,
}

/// A fresh self-signed root named `name`, generated by `openssl` into `dir`.
fn self_signed_root(dir: &Path, name: &str) -> Root {
    let certificate = dir.join(format!("{name}.pem"));
    let output = Command::new("openssl")
        .args([
            "req",
            "-x509",
            "-newkey",
            "ec",
            "-pkeyopt",
            "ec_paramgen_curve:P-256",
            "-nodes",
        ])
        .arg("-keyout")
        .arg(dir.join(format!("{name}.key")))
        .arg("-out")
        .arg(&certificate)
        .args(["-subj", &format!("/CN={name}"), "-days", "36500"])
        .output()
        .unwrap_or_else(|error| {
            panic!("generating the {name} root needs `openssl` on PATH: {error}")
        });
    assert!(
        output.status.success(),
        "openssl must generate the {name} root: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let pem = std::fs::read_to_string(&certificate).expect("the generated root is readable");
    let der =
        CertificateDer::from_pem_slice(pem.as_bytes()).expect("openssl writes one PEM certificate");
    let digest = <sha1::Sha1 as sha1::Digest>::digest(der.as_ref());
    Root {
        pem,
        thumbprint: digest.iter().map(|byte| format!("{byte:02X}")).collect(),
    }
}

/// The bundle a node serves, with a content-derived timestamp as the daemon
/// gives it, so a rotation is a change the guest's store provider sees.
fn bundle(roots: &[&Root]) -> PlatformFiles {
    let pem: String = roots.iter().map(|root| root.pem.as_str()).collect();
    let digest = <sha1::Sha1 as sha1::Digest>::digest(pem.as_bytes());
    let modified_ns =
        u64::from_le_bytes(digest[..8].try_into().expect("eight bytes")) % 1_000_000_000_000;
    PlatformFiles::new(vec![PlatformFile {
        path: BUNDLE_PATH.into(),
        bytes: pem.into_bytes().into(),
        modified_ns,
    }])
    .expect("the bundle's path is one absolute file")
}

/// What the fixture answers for a store holding exactly `roots`.
fn listing(roots: &[&Root]) -> String {
    let mut thumbprints: Vec<&str> = roots.iter().map(|root| root.thumbprint.as_str()).collect();
    thumbprints.sort_unstable();
    format!("roots={} {}", thumbprints.len(), thumbprints.join(","))
}

/// Initializes the fixture with the supplied read-only platform files.
fn prepared_template(runtime: GuestRuntime, served: PlatformFiles) -> Vec<u8> {
    let wasm = wisp_fixtures::dotnet_for("wisp_guest_dotnet_trust", runtime);
    PreInitializer::new()
        .with_pal(InitSandbox::RuntimeBringUp)
        .with_platform_files(served)
        .run(
            &wasm,
            &PreInitRequest {
                module_hash: ModuleHash::of(&wasm),
                init_blob: b"{}".to_vec(),
            },
        )
        .expect("the trust fixture initializes with the supplied platform files")
        .template_wasm
}

struct NoDns;

#[async_trait::async_trait]
impl Resolver for NoDns {
    async fn resolve(&self, host: &str, _: u16) -> Result<Vec<std::net::SocketAddr>, DnsError> {
        panic!("the guest must not resolve {host}: listing the root store needs no lookup")
    }
}

/// A node serving `files`, with the template activated on it and the guest
/// clock at `clock_ms` for the first dispatch.
fn node_serving(files: PlatformFiles, template: &[u8], clock_ms: u64) -> (Reactor, ReturnedGuest) {
    let reactor = Reactor::with_platform_files(
        InstanceId::alloc(),
        HostEgressPolicy::new(Box::new(NoDns), 8, 1 << 20),
        files,
    );
    reactor.context.begin_slice(clock_ms, 1);
    let guest = ReturnedGuest::new(template, &reactor);
    (reactor, guest)
}

async fn the_template_carries_the_store_loaded_at_preparation(runtime: GuestRuntime) {
    wisp_harness::LogCapture::global();
    let dir = tempfile::tempdir().expect("a temporary directory");
    let a = self_signed_root(dir.path(), "root-a");
    let b = self_signed_root(dir.path(), "root-b");
    let template = prepared_template(runtime, bundle(&[&a]));

    let (reactor, mut guest) = node_serving(bundle(&[&b]), &template, PAST_RECHECK_MS);
    let at_boot = guest.answer(&reactor, "/at-boot", 4).await;
    assert_eq!(
        at_boot,
        listing(&[&a]),
        "the application was constructed at preparation, when A was served, and the template \
         carries what its store listed then ({runtime}); logs: {:?}",
        reactor.context.emitted_logs()
    );
}

async fn a_removed_root_is_gone_from_the_prepared_templates_store_after_the_recheck(
    runtime: GuestRuntime,
) {
    wisp_harness::LogCapture::global();
    let dir = tempfile::tempdir().expect("a temporary directory");
    let a = self_signed_root(dir.path(), "root-a");
    let b = self_signed_root(dir.path(), "root-b");
    let template = prepared_template(runtime, bundle(&[&a]));

    let (reactor, mut guest) = node_serving(bundle(&[&b]), &template, PAST_RECHECK_MS);
    let roots = guest.answer(&reactor, "/roots", 4).await;
    assert_eq!(
        roots,
        listing(&[&b]),
        "five seconds of guest time after preparation loaded the store, its next use reloads the \
         served bundle: A's root is gone and B's is trusted ({runtime}); logs: {:?}",
        reactor.context.emitted_logs()
    );
}

async fn the_prepared_templates_store_keeps_its_roots_within_the_recheck_interval(
    runtime: GuestRuntime,
) {
    wisp_harness::LogCapture::global();
    let dir = tempfile::tempdir().expect("a temporary directory");
    let a = self_signed_root(dir.path(), "root-a");
    let b = self_signed_root(dir.path(), "root-b");
    let template = prepared_template(runtime, bundle(&[&a]));

    let (reactor, mut guest) = node_serving(bundle(&[&b]), &template, WITHIN_RECHECK_MS);
    let roots = guest.answer(&reactor, "/roots", 4).await;
    assert_eq!(
        roots,
        listing(&[&a]),
        "within five seconds of guest time since preparation loaded the store, the cached roots \
         still serve: the rotation is not seen yet ({runtime}); logs: {:?}",
        reactor.context.emitted_logs()
    );
}

