//! Writes the managed SDK's copies of the host interface into
//! `guest-sdks/dotnet/Abi/Generated`, from the definitions this crate
//! compiles: the enums a host encodes. The directory holds nothing else, and
//! each run replaces it.

#![forbid(unsafe_code)]

use std::error::Error;
use std::fmt::Write;
use std::path::Path;

use isoplane_abi::dispatch::DispatchKind;
use isoplane_abi::result::{FutureError, ResultRecord};
use isoplane_abi::status::{PollTag, TrapCode, PAYLOAD_SHIFT};
use serde::de::DeserializeOwned;
use serde_reflection::{ContainerFormat, Registry, Tracer, TracerConfig};
use strum::{EnumMessage, VariantArray};

type Generated<T> = Result<T, Box<dyn Error>>;

fn main() -> Generated<()> {
    if cfg!(feature = "rust-guests") {
        return Err(
            "this build has the rust-guests feature, whose variants no shipped host has; run task generate:abi"
                .into(),
        );
    }
    let registry = registry()?;
    let files = [
        (
            "DispatchKind.g.cs",
            postcard_enum::<DispatchKind>(&registry, "DispatchKind", "DispatchKind", "public")?,
        ),
        (
            "FutureError.g.cs",
            postcard_enum::<FutureError>(&registry, "FutureError", "FutureError", "internal")?,
        ),
        (
            "ResultKind.g.cs",
            postcard_enum::<ResultRecord>(&registry, "ResultRecord", "ResultKind", "internal")?,
        ),
        (
            "TrapCode.g.cs",
            numbered_enum("TrapCode", TrapCode::VARIANTS, |code| code as u32)?,
        ),
        (
            "PollTag.g.cs",
            numbered_enum("PollTag", PollTag::VARIANTS, |tag| tag as u32)?,
        ),
        ("PollStatus.g.cs", poll_status()),
    ];
    let directory =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../guest-sdks/dotnet/Abi/Generated");
    match std::fs::remove_dir_all(&directory) {
        Err(error) if error.kind() != std::io::ErrorKind::NotFound => return Err(error.into()),
        _ => {}
    }
    std::fs::create_dir_all(&directory)?;
    for (file, text) in files {
        std::fs::write(directory.join(file), text)?;
    }
    Ok(())
}

/// The layouts Serde gives the enums postcard encodes.
fn registry() -> Generated<Registry> {
    let mut tracer = Tracer::new(TracerConfig::default());
    tracer.trace_simple_type::<DispatchKind>()?;
    tracer.trace_simple_type::<FutureError>()?;
    tracer.trace_simple_type::<ResultRecord>()?;
    Ok(tracer.registry()?)
}

fn header(source: &str) -> String {
    format!(
        "// <auto-generated>\n\
         // This code is generated by `task generate:abi` from {source} in crates/isoplane-abi.\n\
         // DON'T CHANGE THIS DIRECTLY.\n\
         // </auto-generated>\n"
    )
}

struct Member {
    name: String,
    value: u32,
    summary: Option<String>,
}

/// The C# enum `csharp_name` of the Rust enum `T`, which postcard encodes and
/// Serde calls `name`: numbered as Serde numbers its variants and documented
/// as they are.
fn postcard_enum<T>(
    registry: &Registry,
    name: &str,
    csharp_name: &str,
    visibility: &str,
) -> Generated<String>
where
    T: DeserializeOwned + EnumMessage,
    for<'a> &'a T: Into<&'static str>,
{
    let Some(ContainerFormat::Enum(variants)) = registry.get(name) else {
        return Err(format!("{name} is not an enum Serde describes").into());
    };
    let samples = one_of_each_variant::<T>()?;
    let members = variants
        .iter()
        .map(|(value, variant)| Member {
            name: variant.name.clone(),
            value: *value,
            summary: samples
                .iter()
                .find(|sample| Into::<&'static str>::into(*sample) == variant.name)
                .and_then(|sample| sample.get_documentation())
                .map(str::to_owned),
        })
        .collect::<Vec<_>>();
    csharp_enum(csharp_name, visibility, &members)
}

/// A value of each variant of `T`, through which a variant's documentation is
/// read.
fn one_of_each_variant<T: DeserializeOwned>() -> Generated<Vec<T>> {
    let (_, samples) = Tracer::new(TracerConfig::default()).trace_simple_type::<T>()?;
    Ok(samples)
}

/// The C# enum of a Rust enum whose variants set their own numbers.
fn numbered_enum<T>(name: &str, variants: &[T], number: fn(T) -> u32) -> Generated<String>
where
    T: EnumMessage + Into<&'static str> + Copy,
{
    let members = variants
        .iter()
        .map(|variant| Member {
            name: Into::<&'static str>::into(*variant).to_owned(),
            value: number(*variant),
            summary: variant.get_documentation().map(str::to_owned),
        })
        .collect::<Vec<_>>();
    csharp_enum(name, "internal", &members)
}

fn csharp_enum(name: &str, visibility: &str, members: &[Member]) -> Generated<String> {
    let mut text = header(&format!("`{name}`"));
    text.push_str("namespace Isoplane.Abi;\n\n");
    writeln!(
        text,
        "/// <summary><c>{name}</c> of the host interface, with the values a host encodes.</summary>"
    )?;
    writeln!(text, "{visibility} enum {name} : uint\n{{")?;
    for member in members {
        if let Some(summary) = &member.summary {
            writeln!(text, "    /// <summary>{}</summary>", xml(summary))?;
        }
        writeln!(text, "    {} = {},", member.name, member.value)?;
    }
    text.push_str("}\n");
    Ok(text)
}

/// The generated half of the C# `PollStatus`: how a tag and its payload are
/// packed into one status.
fn poll_status() -> String {
    format!(
        "{}namespace Isoplane.Abi;\n\n\
         internal static partial class PollStatus\n{{\n    \
         /// <summary>The status <paramref name=\"tag\"/> names, carrying <paramref name=\"payload\"/>.</summary>\n    \
         private static long Pack(PollTag tag, uint payload) => (long)((ulong)tag | ((ulong)payload << {PAYLOAD_SHIFT}));\n}}\n",
        header("`status::PollStatus::encode` and `status::PAYLOAD_SHIFT`")
    )
}

/// Documentation on one line, escaped for an XML doc comment.
fn xml(documentation: &str) -> String {
    documentation
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}
