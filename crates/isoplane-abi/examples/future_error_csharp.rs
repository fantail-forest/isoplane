//! Writes `guest-sdks/dotnet/Abi/FutureError.g.cs`: the C# enum of
//! `result::FutureError` with the tags a shipped host encodes, read from the
//! variant list the type's `Deserialize` gives its deserializer.

#![forbid(unsafe_code)]

use std::error::Error;
use std::fmt::{self, Write};

use isoplane_abi::result::FutureError;
use serde::de::{Deserialize, Deserializer, Visitor};

fn main() -> Result<(), Box<dyn Error>> {
    if cfg!(feature = "rust-guests") {
        return Err("this build has the rust-guests feature, whose variants the shipped SDK never receives; run task generate:abi, which builds isoplane-abi alone".into());
    }
    let Err(Enum { name, variants }) = FutureError::deserialize(EnumDefinition) else {
        return Err("FutureError deserialized from a deserializer that holds no value".into());
    };
    if variants.is_empty() {
        return Err("FutureError did not ask its deserializer for an enum".into());
    }
    let mut text = format!(
        "// <auto-generated>\n\
         // This code is generated by `task generate:abi` from isoplane-abi's {name}.\n\
         // DON'T CHANGE THIS DIRECTLY.\n\
         // </auto-generated>\n\
         namespace Isoplane.Abi;\n\
         \n\
         /// <summary><c>isoplane-abi::result::{name}</c>, with the tags a host encodes.</summary>\n\
         internal enum {name} : uint\n\
         {{\n"
    );
    // postcard writes a variant as its position in this list.
    for (tag, variant) in variants.iter().enumerate() {
        writeln!(text, "    {variant} = {tag},")?;
    }
    text.push_str("}\n");
    std::fs::write(
        concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../guest-sdks/dotnet/Abi/FutureError.g.cs"
        ),
        text,
    )?;
    Ok(())
}

/// A deserializer that holds no value: it answers a request for an enum with
/// the name and variants the type passed, and any other request with nothing.
struct EnumDefinition;

#[derive(Debug, Default)]
struct Enum {
    name: &'static str,
    variants: &'static [&'static str],
}

impl fmt::Display for Enum {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(formatter, "the enum {}", self.name)
    }
}

impl Error for Enum {}

impl serde::de::Error for Enum {
    fn custom<T: fmt::Display>(_: T) -> Self {
        Self::default()
    }
}

impl<'de> Deserializer<'de> for EnumDefinition {
    type Error = Enum;

    fn deserialize_any<V: Visitor<'de>>(self, _: V) -> Result<V::Value, Enum> {
        Err(Enum::default())
    }

    fn deserialize_enum<V: Visitor<'de>>(
        self,
        name: &'static str,
        variants: &'static [&'static str],
        _: V,
    ) -> Result<V::Value, Enum> {
        Err(Enum { name, variants })
    }

    serde::forward_to_deserialize_any! {
        bool i8 i16 i32 i64 i128 u8 u16 u32 u64 u128 f32 f64 char str string
        bytes byte_buf option unit unit_struct newtype_struct seq tuple
        tuple_struct map struct identifier ignored_any
    }
}
