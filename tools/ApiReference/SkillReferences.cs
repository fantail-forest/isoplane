using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

/// <summary>
/// The reference files of the <c>isoplane</c> agent skill, one directory per SDK package: the customer
/// guides and reference pages that package's code needs, flattened from the site's MDX to markdown a
/// coding agent reads outside the site. The SDK build assembles the skill from whichever parts the
/// project's packages carry, so each part also gets a README that lists its files for the skill's index.
/// </summary>
internal static class SkillReferences
{
    private const string Site = "https://isoplane.dev/docs/";
    private static readonly Regex Frontmatter = new(@"\A---\r?\n(.*?)\r?\n---\r?\n", RegexOptions.Singleline | RegexOptions.CultureInvariant);
    private static readonly Regex Import = new(@"^import\s+(\w+)\s+from\s+'([^']+)';?\s*$", RegexOptions.Multiline | RegexOptions.CultureInvariant);
    private static readonly Regex NamedImport = new(@"^import\s+\{[^}]*\}\s+from\s+'[^']+';?\s*\r?\n", RegexOptions.Multiline | RegexOptions.CultureInvariant);
    private static readonly Regex PlatformToggle = new(@"^<PlatformToggle />\s*\r?\n", RegexOptions.Multiline | RegexOptions.CultureInvariant);
    private static readonly Regex OnlyOnOpen = new(@"^<OnlyOn platforms=""([^""]+)"">\s*$", RegexOptions.Multiline | RegexOptions.CultureInvariant);
    private static readonly Regex OnlyOnClose = new(@"^</OnlyOn>\s*\r?\n", RegexOptions.Multiline | RegexOptions.CultureInvariant);
    private static readonly Regex HeadingId = new(@"^(#{1,6} .*?)\s*\{#[^}]+\}\s*$", RegexOptions.Multiline | RegexOptions.CultureInvariant);
    private static readonly Regex Since = new(@" ?:since\[[^\]]+\]", RegexOptions.CultureInvariant);
    private static readonly Regex Generated = new(@"^<!-- Generated by tools/ApiReference\. -->\s*$", RegexOptions.Multiline | RegexOptions.CultureInvariant);
    private static readonly Regex RelativeLink = new(@"\]\((?!https?://|#|mailto:)([^)#\s]+?)\.mdx?(#[^)]*)?\)", RegexOptions.CultureInvariant);
    private static readonly Regex Heading = new(@"^(#{1,6}) ", RegexOptions.Multiline | RegexOptions.CultureInvariant);
    private static readonly Dictionary<string, string> Platforms = new() { ["mac"] = "macOS", ["win"] = "Windows", ["linux"] = "Linux" };

    /// <summary>A package's part of the skill: the pages it carries, and the bundles it concatenates into one file.</summary>
    private sealed record Part(string Name, string[] Pages, Bundle[] Bundles);

    /// <summary>One output file made from several pages: the first as it is, the others with their headings one level down.</summary>
    private sealed record Bundle(string Output, string Directory, string? First);

    private static readonly Part[] Parts =
    [
        new("sdk",
            ["concepts/dotnet-runtime-differences", "concepts/library-compatibility", "concepts/resource-limits", "concepts/application-lifecycle",
             "how-to/install", "how-to/handle-requests-without-aspnet", "how-to/run-and-rebuild", "how-to/debug-an-application", "how-to/local-settings",
             "how-to/find-and-fix-blocking-calls", "how-to/handle-uploads-and-generated-files", "how-to/test-an-application", "how-to/troubleshooting",
             "reference/error-codes", "reference/project-settings", "reference/launch-settings", "reference/vscode-launch", "reference/project-templates",
             "reference/telemetry", "reference/sdk"],
            [new("reference/cli", "reference/cli", "reference/cli"),
             new("reference/api/Isoplane.Sdk", "reference/sdk/Isoplane.Sdk", "reference/sdk/Isoplane.Sdk/Isoplane.Sdk"),
             new("reference/api/Isoplane.Testing", "reference/sdk/Isoplane.Testing", "reference/sdk/Isoplane.Testing/Isoplane.Testing")]),
        new("aspnetcore",
            ["how-to/onboard-an-application", "how-to/connect-postgresql", "how-to/keep-data-protection-keys", "how-to/run-work-on-a-schedule"],
            [new("reference/api/Isoplane.AspNetCore", "reference/sdk/Isoplane.AspNetCore", "reference/sdk/Isoplane.AspNetCore/Isoplane.AspNetCore")]),
        new("opentelemetry", [],
            [new("reference/api/Isoplane.OpenTelemetry", "reference/sdk/Isoplane.OpenTelemetry", "reference/sdk/Isoplane.OpenTelemetry/Isoplane.OpenTelemetry")]),
        new("dataprotection-efcore", [],
            [new("reference/api/Isoplane.AspNetCore.DataProtection.EntityFrameworkCore", "reference/sdk/Isoplane.AspNetCore.DataProtection.EntityFrameworkCore",
                 "reference/sdk/Isoplane.AspNetCore.DataProtection.EntityFrameworkCore/Isoplane.AspNetCore.DataProtection.EntityFrameworkCore")]),
    ];

    /// <summary>
    /// Writes the skill's base <c>SKILL.md</c> and each part under <paramref name="output"/>, laid out as a
    /// package carries them: <c>SKILL.md</c> beside <c>references/&lt;part&gt;/</c>. Replaces whatever is there.
    /// </summary>
    internal static void Export(DirectoryInfo docs, DirectoryInfo skill, DirectoryInfo output)
    {
        if (output.Exists) output.Delete(recursive: true);
        output.Create();
        File.Copy(Path.Combine(skill.FullName, "SKILL.md"), Path.Combine(output.FullName, "SKILL.md"));
        foreach (var part in Parts)
        {
            var directory = Directory.CreateDirectory(Path.Combine(output.FullName, "references", part.Name)).FullName;
            var listed = new List<(string Title, string Path)>();
            foreach (var page in part.Pages)
            {
                var (title, text) = Flatten(docs, page + ".md");
                Write(Path.Combine(directory, page + ".md"), text);
                listed.Add((title, page + ".md"));
            }
            foreach (var bundle in part.Bundles)
            {
                var sources = Directory.EnumerateFiles(Path.Combine(docs.FullName, bundle.Directory), "*.md", SearchOption.AllDirectories)
                    .Select(path => Path.GetRelativePath(docs.FullName, path).Replace(Path.DirectorySeparatorChar, '/'))
                    .Where(path => path != bundle.First + ".md").Order(StringComparer.Ordinal).ToList();
                if (bundle.First is not null) sources.Insert(0, bundle.First + ".md");
                if (sources.Count == 0) throw new InvalidOperationException($"{bundle.Directory} has no pages for {bundle.Output}.");
                var pages = sources.Select(source => Flatten(docs, source)).ToArray();
                var text = string.Join("\n\n", pages.Select((page, index) => index == 0 ? page.Text : Demote(page.Text)));
                Write(Path.Combine(directory, bundle.Output + ".md"), text);
                listed.Add((pages[0].Title, bundle.Output + ".md"));
            }
            var section = File.ReadAllText(Path.Combine(skill.FullName, "sections", part.Name + ".md")).TrimEnd();
            var files = string.Join("\n", listed.Select(file => $"- [{file.Title}](references/{part.Name}/{file.Path})"));
            Write(Path.Combine(directory, "README.md"), section + "\n\n" + files);
        }
    }

    /// <summary>The page as plain markdown: its title, and its body with the site's MDX resolved and its links absolute.</summary>
    private static (string Title, string Text) Flatten(DirectoryInfo docs, string page)
    {
        var text = File.ReadAllText(Path.Combine(docs.FullName, page)).Replace("\r\n", "\n");
        var title = "";
        text = Frontmatter.Replace(text, match =>
        {
            foreach (var line in match.Groups[1].Value.Split('\n'))
                if (line.StartsWith("title:", StringComparison.Ordinal))
                {
                    var value = line["title:".Length..].Trim();
                    title = value.StartsWith('"') ? JsonSerializer.Deserialize<string>(value)! : value;
                }
            return "";
        }, 1);
        var directory = Path.GetDirectoryName(page)!.Replace(Path.DirectorySeparatorChar, '/');
        text = Import.Replace(text, match =>
        {
            var included = Path.Combine(docs.FullName, directory, match.Groups[2].Value);
            var body = File.ReadAllText(included).Replace("\r\n", "\n").Trim();
            text = text.Replace($"<{match.Groups[1].Value} />", body);
            return "";
        });
        text = NamedImport.Replace(text, "");
        text = PlatformToggle.Replace(text, "");
        text = OnlyOnOpen.Replace(text, match => "**On " + string.Join(" and ", match.Groups[1].Value.Split(' ', StringSplitOptions.RemoveEmptyEntries).Select(platform => Platforms[platform])) + ":**");
        text = OnlyOnClose.Replace(text, "");
        text = HeadingId.Replace(text, "$1");
        text = Since.Replace(text, "");
        text = Generated.Replace(text, "");
        text = RelativeLink.Replace(text, match =>
        {
            var target = Path.GetFullPath(Path.Combine("/", directory, match.Groups[1].Value))[1..].Replace(Path.DirectorySeparatorChar, '/');
            return $"]({Site}{target}{match.Groups[2].Value})";
        });
        text = text.Trim() + "\n";
        if (text.StartsWith("# ", StringComparison.Ordinal)) title = text[2..text.IndexOf('\n')].Trim();
        else if (title.Length != 0) text = $"# {title}\n\n{text}";
        else throw new InvalidOperationException($"{page} has neither a title nor a heading.");
        return (title, text);
    }

    /// <summary>Every heading one level down, outside code fences, so a page nests under the bundle's first.</summary>
    private static string Demote(string text)
    {
        var lines = text.Split('\n');
        var fenced = false;
        for (var i = 0; i < lines.Length; i++)
        {
            if (lines[i].StartsWith("```", StringComparison.Ordinal)) fenced = !fenced;
            else if (!fenced) lines[i] = Heading.Replace(lines[i], "#$1 ", 1);
        }
        return string.Join("\n", lines);
    }

    private static void Write(string path, string text)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, text.TrimEnd() + "\n", new UTF8Encoding(false));
    }
}
