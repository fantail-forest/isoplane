using System.CommandLine;
using System.CommandLine.Help;
using System.Text;
using Isoplane.Cli;

/// <summary>
/// The CLI reference, from the command definitions the CLI parses with: an overview page listing the
/// commands, and a page for each with its arguments, options and subcommands. Hidden commands and
/// options are left out. A visible command, argument or option without a description fails generation.
/// </summary>
internal static class Cli
{
    private const string Directory = "cli";

    internal static void Generate(Dictionary<string, string> output)
    {
        var root = CliCommandLine.Create();
        var commands = root.Subcommands.Where(command => !command.Hidden).ToArray();
        // The directory's category takes the overview page's title and link, and its own position.
        output.Add(Directory + "/_category_.json", "{\"position\": 6}\n");
        output.Add(Directory + ".md", Overview.Replace("{commands}", "| Command | Description |\n| --- | --- |\n" + string.Join("\n",
            commands.Select(command => $"| [`isoplane {command.Name}`]({Directory}/{command.Name}.md){Since.Mark(Item(command.Name))} | {Described(command)} |"))));
        foreach (var command in commands)
        {
            var page = new StringBuilder($"---\ntitle: isoplane {command.Name}\nmdx:\n  format: md\n---\n\n");
            Section(page, command, command.Name, level: 1);
            output.Add($"{Directory}/{command.Name}.md", page.ToString().TrimEnd() + "\n\n<!-- Generated by tools/ApiReference. -->\n");
        }
    }

    private static string Item(string path) => "cli#" + path;

    private static void Section(StringBuilder page, Command command, string path, int level)
    {
        var subcommands = command.Subcommands.Where(subcommand => !subcommand.Hidden).ToArray();
        var arguments = command.Arguments.Where(argument => !argument.Hidden).ToArray();
        var options = command.Options.Where(option => !option.Hidden && option is not HelpOption and not VersionOption).ToArray();
        page.Append($"{new string('#', level)} isoplane {path}{Since.Mark(Item(path))}\n\n{Described(command)}\n\n");
        var usage = string.Join(' ', new[] { "isoplane", path }
            .Concat(arguments.Select(argument => argument.Arity.MinimumNumberOfValues == 0 ? $"[{argument.Name}]" : $"<{argument.Name}>"))
            .Concat(subcommands.Length > 0 ? ["<command>"] : [])
            .Concat(options.Length > 0 ? ["[options]"] : []));
        page.Append($"```bash\n{usage}\n```\n\n");
        if (arguments.Length > 0)
            page.Append("| Argument | Description |\n| --- | --- |\n").AppendJoin('\n', arguments.Select(argument =>
                $"| `{argument.Name}`{Since.Mark(Item($"{path}#{argument.Name}"))} | {Described(argument)} |")).Append("\n\n");
        if (options.Length > 0)
            page.Append("| Option | Description |\n| --- | --- |\n").AppendJoin('\n', options.Select(option =>
                $"| `{Spelled(option)}`{Since.Mark(Item($"{path}#{option.Name}"))} | {(option.Required ? "Required. " : "")}{Described(option)} |")).Append("\n\n");
        if (subcommands.Length > 0)
            page.Append("| Command | Description |\n| --- | --- |\n").AppendJoin('\n', subcommands.Select(subcommand =>
                $"| [`isoplane {path} {subcommand.Name}`](#{Anchor($"isoplane {path} {subcommand.Name}")}) | {Described(subcommand)} |")).Append("\n\n");
        foreach (var subcommand in subcommands) Section(page, subcommand, $"{path} {subcommand.Name}", level + 1);
    }

    /// <summary>The option as it is typed: short aliases first, and a value placeholder unless it is a flag.</summary>
    private static string Spelled(Option option)
    {
        var names = option.Aliases.Append(option.Name).OrderBy(name => name.Length).ThenBy(name => name, StringComparer.Ordinal);
        return string.Join(", ", names) + (option.ValueType == typeof(bool) ? "" : $" <{option.Name.TrimStart('-')}>");
    }

    private static string Anchor(string heading) => heading.ToLowerInvariant().Replace(' ', '-');

    private static string Described(Symbol symbol) => string.IsNullOrWhiteSpace(symbol.Description)
        ? throw new InvalidOperationException($"{symbol.Name} has no description in CliCommandLine.cs.")
        : symbol.Description.Replace("<", "&lt;");

    private const string Overview = """
---
title: CLI commands
mdx:
  format: md
---

# CLI commands

The commands of the `isoplane` CLI, with the arguments and options of each. They are generated from the definitions the CLI parses with, for the source version used to build this documentation. `isoplane --help` and `isoplane <command> --help` print the same for the version you have installed; `isoplane --version` prints that version.

[Install the CLI](../how-to/install.md) describes installing it and setting up shell completion.

{commands}

<!-- Generated by tools/ApiReference. -->
""";
}
